// Generates server/src/web/embedded.ts from web/dist so `bun build --compile` embeds the UI.
import { readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { contentType } from "../server/src/web/static";

const root = resolve(import.meta.dir, "..");
const dist = join(root, "web", "dist");

const walk = (dir: string, url: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((dirent) =>
    dirent.isDirectory()
      ? walk(join(dir, dirent.name), `${url}${dirent.name}/`)
      : dirent.isFile()
        ? [`${url}${dirent.name}`]
        : [],
  );

const files = walk(dist, "/").sort();
if (!files.includes("/index.html")) throw new Error("web/dist/index.html not found; build the web app first");

const imports = files.map((file, index) => `import f${index} from "../../../web/dist${file}" with { type: "file" };`);
const entries = files.map(
  (file, index) => `  [${JSON.stringify(file)}, { path: f${index}, type: ${JSON.stringify(contentType(file))} }],`,
);
writeFileSync(
  join(root, "server", "src", "web", "embedded.ts"),
  `// @ts-nocheck
// GENERATED by scripts/gen-embed.ts - do not edit.\n${imports.join("\n")}\n\nexport const embeddedFiles: Map<string, { path: string; type: string }> = new Map([\n${entries.join("\n")}\n]);\n`,
);
// The generated file was server/src/embedded.ts before the server layout move. A stale copy in an old checkout is removed.
rmSync(join(root, "server", "src", "embedded.ts"), { force: true });
console.log(`embedded ${files.length} files`);
