import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { isIP } from "node:net";
import path from "node:path";
import type { Flags } from "./args";
import { ExitError } from "./creds";
import type { HubClient } from "./hub";

export interface Enrollment {
  hub_keys: { public_key: string }[];
}

/** Checks the hub's enrollment response. An old hub sends `oidc` and no `hub_keys`. */
export function requireHubKeys(value: unknown): Enrollment {
  const keys = (value as { hub_keys?: unknown } | null | undefined)?.hub_keys;

  if (
    !Array.isArray(keys) ||
    keys.length === 0 ||
    !keys.every((key) => typeof (key as { public_key?: unknown } | null)?.public_key === "string")
  ) {
    throw new ExitError("the hub did not return a hub key. Upgrade the hub to a version that supports hub keys.", 1);
  }

  return value as Enrollment;
}

const quote = (text: string) => JSON.stringify(text); // a JSON string is a valid TOML basic string
const list = (items: string[]) => `[${items.map(quote).join(", ")}]`;
const isAbs = (item: string) => item.startsWith("/") || /^[A-Za-z]:[\\/]/.test(item);
const csv = (text: string) =>
  text
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);

/** A complete node `config.toml`. Values that come from the hub are filled in. Optional keys are left out. */
export function renderNodeConfig(options: {
  hub: string;
  enrollment: Enrollment;
  listen: string;
  port: number;
  names: string[];
  name?: string;
  roots?: string[];
  serviceUser?: string;
  stateDir?: string;
}): string {
  return [
    `# Node configuration generated by "claude-rc node config" from ${options.hub}.`,
    "# The hub key is a public key. It is not secret.",
    'mode = "node"',
    ...(options.name ? [`name = ${quote(options.name)}`] : []),
    `port = ${options.port}`,
    `host = ${quote(options.listen)}`,
    ...(options.roots?.length || options.serviceUser
      ? [
          "",
          "[instance]",
          ...(options.serviceUser ? [`service_user = ${quote(options.serviceUser)}`] : []),
          ...(options.roots?.length ? [`roots = ${list(options.roots)}`] : []),
        ]
      : []),
    "",
    "[tls]",
    `state_dir = ${quote(options.stateDir ?? "/var/lib/claude-rc-launcher")}`,
    `names = ${list(options.names)}`,
    "",
    ...options.enrollment.hub_keys.flatMap((hub_key) => [
      "[[node_auth.hub_key]]",
      `public_key = ${quote(hub_key.public_key)}`,
      "",
    ]),
  ].join("\n");
}

export const DEFAULT_NODE_CONFIG = "/etc/claude-rc-launcher/config.toml";

/** The file operations of `node config`, so that tests do not touch /etc or run sudo. */
export interface NodeFs {
  exists(path: string): boolean;
  /** Creates the parent directory and writes the file. Throws on any error. */
  write(path: string, text: string): void;
  /** Copies the file to `<path>.bak`. */
  backup(path: string): void;
  /** The same as backup (when asked) and write, run through `sudo`. */
  sudoWrite(path: string, text: string, backup: boolean): void;
  isRoot(): boolean;
}

export const realNodeFs: NodeFs = {
  exists: (file) => existsSync(file),
  write(line, text) {
    mkdirSync(path.dirname(line), { recursive: true });
    writeFileSync(line, text, { mode: 0o644 });
  },
  backup: (item) => {
    copyFileSync(item, `${item}.bak`);
  },
  sudoWrite(item, text, backup) {
    const run = (args: string[], input?: string) => {
      const spawnSyncReturns = spawnSync("sudo", args, {
        ...(input !== undefined ? { input } : {}),
        stdio: [input !== undefined ? "pipe" : "inherit", "ignore", "inherit"],
      });
      if (spawnSyncReturns.error) throw new ExitError(`cannot run sudo: ${spawnSyncReturns.error.message}`, 1);
      if (spawnSyncReturns.status !== 0)
        throw new ExitError(`"sudo ${args[0]}" failed (exit ${spawnSyncReturns.status})`, 1);
    };

    run(["mkdir", "-p", path.dirname(item)]);
    if (backup) run(["cp", "-p", item, `${item}.bak`]);
    run(["tee", item], text);
  },
  isRoot: () => process.getuid?.() === 0,
};

export interface NodeFlags {
  listen: string;
  port: number;
  names: string[];
  roots?: string[];
  name?: string;
  serviceUser?: string;
}

/** The host of an `--url` value, without IPv6 brackets. `undefined` when the value is not a URL (the caller reports that). */
export function urlHost(url: string | undefined): string | undefined {
  if (!url) return undefined;

  try {
    return new URL(url).hostname.replace(/^\[(.*)\]$/, "$1") || undefined;
  } catch {
    return undefined;
  }
}

/**
 * Validates the flags that `node config` and `node setup` share. `hubHost` is the host that the hub will connect to
 * (the host of `--url` in `node setup`). The certificate must cover it, so it is added to the names.
 */
export function nodeFlags(flags: Flags, usage: string, hubHost?: string): NodeFlags {
  if (!flags.listen) throw new ExitError(`--listen is required: the private address this node binds. ${usage}`, 1);
  const names = csv(flags.names ?? "");
  const bad = names.find((name) => !isIP(name) && !/^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$/.test(name));
  if (bad)
    throw new ExitError(
      `--names has an invalid name: ${JSON.stringify(bad)}. Names are DNS names or IP addresses, separated by commas without spaces`,
      1,
    );
  // The hub will almost always connect to the address that the node binds, so the certificate must cover it.
  if (isIP(flags.listen) && flags.listen !== "0.0.0.0" && flags.listen !== "::" && !names.includes(flags.listen))
    names.push(flags.listen);
  // The same holds for the host in --url: the hub checks the certificate against that name, so it must be listed.
  if (
    hubHost &&
    (isIP(hubHost) || /^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$/.test(hubHost)) &&
    !names.some((name) => name.toLowerCase() === hubHost.toLowerCase())
  )
    names.push(hubHost);
  if (names.length === 0)
    throw new ExitError(
      `--names is required when --listen is not an IP address: the DNS names and IP addresses of THIS node that the hub will use in --url. ${usage}`,
      1,
    );
  const port = flags.port === undefined ? 8443 : Number(flags.port);
  if (!Number.isInteger(port) || port < 1 || port > 65535)
    throw new ExitError("--port must be a number from 1 to 65535", 1);
  const roots = flags.roots === undefined ? undefined : csv(flags.roots);
  for (const root of roots ?? [])
    if (!isAbs(root)) throw new ExitError(`--roots entries must be absolute paths: ${root}`, 1);
  const serviceUser = flags["service-user"];
  if (serviceUser !== undefined && !/^[a-z_][a-z0-9_-]{0,31}$/.test(serviceUser))
    throw new ExitError(`--service-user is not a valid user name: ${serviceUser}`, 1);
  return {
    listen: flags.listen,
    port,
    names,
    ...(roots?.length ? { roots } : {}),
    ...(flags.name ? { name: flags.name } : {}),
    ...(serviceUser ? { serviceUser } : {}),
  };
}

/**
 * `claude-rc node config`: writes the node configuration for this machine. The file is written by this command
 * (through sudo when the directory is not writable), and a single status line is printed. `--output -` prints it.
 */
export async function nodeConfig(options: {
  flags: Flags;
  hubUrl: string;
  hub: HubClient;
  out: (line: string) => void;
  fs?: NodeFs;
}): Promise<void> {
  const usage =
    "usage: claude-rc node config --listen <address> [--names <name,name,...>] [--port <n>] [--name <n>] [--roots </dir,/dir>] [--service-user <user>] [--output <file>|-] [--force]";
  const { flags } = options;
  const fs = options.fs ?? realNodeFs;
  const nf = nodeFlags(flags, usage);
  const file = flags.output ?? DEFAULT_NODE_CONFIG;
  if (file !== "-" && !isAbs(file)) throw new ExitError(`--output must be an absolute path or "-": ${file}`, 1);
  const exists = file !== "-" && fs.exists(file);
  if (exists && !flags.force)
    throw new ExitError(`${file} already exists. Use --force to replace it (the old file is kept as ${file}.bak)`, 1);

  const enrollment = requireHubKeys(await options.hub.request<unknown>("GET", "/cli/api/node-enrollment"));
  const text = renderNodeConfig({ hub: options.hubUrl, enrollment, ...nf });

  if (file === "-") {
    options.out(text);
    return;
  }

  try {
    if (exists) fs.backup(file);
    fs.write(file, text);
    options.out(`wrote ${file}`);
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;

    if ((code !== "EACCES" && code !== "EPERM") || fs.isRoot() || process.platform === "win32") {
      throw new ExitError(`cannot write ${file}: ${(error as Error).message}`, 1);
    }

    fs.sudoWrite(file, text, exists);
    options.out(`wrote ${file} (with sudo)`);
  }
}
